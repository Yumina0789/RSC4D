pub const FILETIME_UNIX_EPOCH_DIFF: i64 = 11_644_473_600;

pub fn unix_to_filetime(unix: i64) -> u64 {
    ((unix + FILETIME_UNIX_EPOCH_DIFF) * 10_000_000) as u64
}

pub fn filetime_to_unix(filetime: u64) -> i64 {
    (filetime / 10_000_000) as i64 - FILETIME_UNIX_EPOCH_DIFF
}

pub fn random16() -> [u8; 16] {
    let mut out = [0u8; 16];
    getrandom::getrandom(&mut out).expect("system CSPRNG unavailable");
    out
}
